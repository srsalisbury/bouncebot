// Generates public/logo_color_halo.svg: the BounceBot mark with a white
// "halo" layered behind it, for embedding in the center of a QR code without
// the code's dark modules showing through.
//
// The halo is built from the logo's own first <path> - a solid, uncut blob
// that every other shape in the logo (the white path drawn on top to carve
// out the ring outline, the colored dots) sits entirely inside. Duplicating
// just that path, scaled up around the logo's own center and filled white,
// gives a ring that exactly follows the mark's silhouette instead of a
// generic square/circle plate.
//
// This is a manual, build-independent step - like `npm run generate` (buf)
// for the proto bindings, its output is committed to git, not regenerated on
// every `dev`/`build`. Run after editing public/logo_color.svg:
//   npm run generate:logo-halo
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { JSDOM } from 'jsdom'

const __dirname = dirname(fileURLToPath(import.meta.url))
const SRC_PATH = join(__dirname, '../public/logo_color.svg')
const OUT_PATH = join(__dirname, '../public/logo_color_halo.svg')

// How far the halo bleeds beyond the mark's own outline, as a fraction of
// its size - sized to roughly match the width of the logo's own white
// strokes (the negative space carved out of the black ring), not the
// thinner black outline around them.
const HALO_SCALE = 1.35

function main() {
  const svgText = readFileSync(SRC_PATH, 'utf8')

  const { window } = new JSDOM()
  const root = new window.DOMParser().parseFromString(svgText, 'image/svg+xml').documentElement

  const viewBox = root.getAttribute('viewBox')
  if (!viewBox) throw new Error('logo svg: no viewBox attribute')
  // path1 (the halo source) is a single closed path that self-intersects
  // where its 4 loops overlap. The root's fill-rule:evenodd is what turns
  // that self-intersection into the smooth pinwheel silhouette instead of a
  // notched/blocky one - carry it over onto the generated root too.
  const rootStyle = root.getAttribute('style') ?? ''
  const [vx, vy, vw, vh] = viewBox.split(/\s+/).map(Number)
  const cx = vx + vw / 2
  const cy = vy + vh / 2

  // The halo is the mark's own silhouette scaled up around its center, so it
  // extends past the original viewBox - and since this file is loaded via
  // <img>, anything outside the viewBox gets hard-clipped, not just
  // overflow-hidden. Expand the viewBox by the same scale, around the same
  // center, so the enlarged halo has room without clipping.
  const outViewBox = [
    cx - (vw * HALO_SCALE) / 2,
    cy - (vh * HALO_SCALE) / 2,
    vw * HALO_SCALE,
    vh * HALO_SCALE,
  ].join(' ')

  const haloPath = root.querySelector('path')
  if (!haloPath) throw new Error('logo svg: no <path> found')

  // Flatten the halo path's ancestor <g transform="..."> chain (outermost
  // first), so the scaled duplicate stays aligned with the original instead
  // of drifting off-center.
  const transforms = []
  for (let el = haloPath.parentElement; el && el !== root; el = el.parentElement) {
    const t = el.getAttribute('transform')
    if (t) transforms.unshift(t)
  }

  const serializer = new window.XMLSerializer()
  const rawInner = Array.from(root.children)
    .map((child) => serializer.serializeToString(child))
    .join('\n  ')

  const composite = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!-- Generated by scripts/generate-logo-halo.js from logo_color.svg - do not edit directly. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${outViewBox}" style="${rootStyle}">
  <g fill="#fff" transform="translate(${cx},${cy}) scale(${HALO_SCALE}) translate(${-cx},${-cy})">
    <g transform="${transforms.join(' ')}"><path d="${haloPath.getAttribute('d')}"/></g>
  </g>
  ${rawInner}
</svg>
`

  writeFileSync(OUT_PATH, composite)
  console.log(`Wrote ${OUT_PATH}`)
}

main()
